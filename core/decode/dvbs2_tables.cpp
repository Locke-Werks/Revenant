// The parity bit accumulator addresses of ETSI EN 302 307-1 V1.4.1 (2014-11)
// annex B, for the two normal-frame codes the GOES-R Rebroadcast uses:
// table B.6 (rate 2/3) and table B.11 (rate 9/10).
//
// ETSI holds the rights in the standard's text. These are the clause-cited
// constants a receiver needs to interoperate with the code, transcribed row
// for row in the order the tables print them (each table read down its left
// column and then down the next), and nothing else of the document is
// reproduced. Flagged for the owner to review before release.
//
// Transcribed from the PDF text of V1.4.1 fetched 2026-11-02 from etsi.org.
// Checked on transcription: B.6 has k/360 = 120 rows and B.11 has 162, every
// address is below n - k (21600 and 6480), and each row's first address
// runs 0, 1, ... modulo q (60 and 18) the way both tables print, which is
// what confirms the column order. The round trip in tests/decode/test_grb.cpp
// checks the encoder built on them against the decoder built on them, which
// would agree on a mistyped entry too; the row checks are what guard that.

