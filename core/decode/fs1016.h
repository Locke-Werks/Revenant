// FS-1016 CELP, the 4800 bit/s US Government code excited linear prediction
// vocoder: 144-bit frames in, 240 samples of 8 kHz PCM out, every 30 ms. The
// encoder is here too, for the tests and for a modulator that wants to carry
// clear CELP voice.
//
// SPECIFICATION
//
// Implements FED-STD-1016, "Telecommunications: Analog to Digital Conversion
// of Radio Voice by 4,800 bit/second Code Excited Linear Prediction (CELP)",
// 14 February 1991. Read as the scanned copy served by EverySpec,
// https://everyspec.com/FED-STD/download.php?spec=FED-STD-1016.023395.pdf,
// retrieved 2026-11-02. A US Government work, so the tables below are
// transcribed from it; every table was read off the page images, not the
// PDF's OCR layer, which garbles digits.
//
// Clauses used: 2 (frame and subframe), 3.2.3 and 3.10.1 (amplitude scale),
// 3.2.5 (perceptual weighting, encoder only), 3.3.1 and 3.3.2 (the stochastic
// code book and how the 512 codes are cut from it), 3.4 (stochastic gain
// table), 3.5.1 to 3.5.5 (adaptive codes, interpolation, the 256-entry
// transmission table and the delta coding of subframes 2 and 4), 3.6
// (adaptive gain table), 3.7.1 to 3.7.3 (LSP table and subframe weighting),
// 3.8.2 to 3.8.4 (bit assignment, sync, expansion bit) and 3.9 (the (15,11)
// Hamming code).
//
// WHERE THE DOCUMENT IS SILENT OR DISAGREES WITH ITSELF
//
//  1. 3.4 prints stochastic gain index 10 as "98". Indices 0 to 15 are the
//     negatives of 31 down to 16 everywhere else in the table, and 21 is 98,
//     so index 10 is taken as -98: a dropped minus sign.
//  2. 3.5.3's worked example says the value R'11 is "interpolated element
//     -56". In the same example R'0 is element -66, which makes R'11 element
//     -55. The positional rule the paragraph states (weight j multiplies the
//     element j places after the one being interpolated, and an element
//     inside the code being built is its already interpolated value) is
//     followed, and the parenthetical is treated as a slip.
//  3. The standard never says how LSPs become filter coefficients. The usual
//     sum and difference polynomial construction is used, with the lowest LSP
//     a root of the sum polynomial P(z) = A(z) + z^-11 A(1/z).
//  4. Nothing says what the "previous frame" LSPs and adaptive code are before
//     the first frame. The decoder starts from the LSPs of a flat spectrum,
//     k * 4000/11 Hz, and adaptive code index 0.
//  5. Nothing says what to do with LSPs that arrive non-monotonic after a
//     channel error. They are sorted before use.
//  6. 3.1.2 and 3.10.3 allow a postfilter and error-rate smoothing without
//     defining either. The postfilter here is an ordinary pole-zero short-term
//     postfilter, off by default; smoothing is not implemented.
//  7. 3.7.2 recommends a 30 ms Hamming analysis window over the last two
//     subframes of this frame and the first two of the next. The encoder does
//     that, which is why it runs one frame behind its input.
//
// CLEAN ROOM
//
// No CELP implementation was read: not the CELP 3.2a reference code, not any
// library's. The code book program and the interpolation weight program in
// 3.3.1 and 3.5.3 are the standard's own FORTRAN, re-expressed here.

#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <span>
#include <string>
#include <vector>

namespace revenant::decode {

// Clause 2: 144 bits and 240 samples per frame, four subframes of 60.
inline constexpr std::size_t kFs1016FrameBits = 144;
inline constexpr std::size_t kFs1016FrameSamples = 240;
inline constexpr std::size_t kFs1016SubframeSamples = 60;
inline constexpr std::size_t kFs1016Subframes = 4;

// 3.3: 512 codes cut from a 1082-element book.
inline constexpr std::size_t kFs1016StochasticBook = 1082;
inline constexpr std::size_t kFs1016StochasticCodes = 512;
// 3.5.1: the adaptive register holds 147 elements; 3.5.2: 256 codes.
inline constexpr std::size_t kFs1016AdaptiveRegister = 147;
inline constexpr std::size_t kFs1016AdaptiveCodes = 256;

using Fs1016Bits = std::array<std::uint8_t, kFs1016FrameBits>;

// The transmitted quantities of one frame, as indices. pd holds what goes on
// the wire: 8 bits for subframes 1 and 3 (the 3.5.4 hex value), 6 bits for 2
// and 4 (the 3.5.5 offset).
struct Fs1016Params {
    std::array<std::uint8_t, 10> lsp{};  // 3.7.2 table index per LSP
    std::array<std::uint8_t, 4> pd{};
    std::array<std::uint8_t, 4> pg{};    // 3.6 index
    std::array<std::uint16_t, 4> ci{};   // 3.3.2 code number, 0..511
    std::array<std::uint8_t, 4> cg{};    // 3.4 index
    std::uint8_t sp = 0;                 // 3.8.4 expansion bit
};

// The book, element 0 first, generated by the 3.3.1 program.
const std::array<std::int8_t, kFs1016StochasticBook>& fs1016_stochastic_book();
// 3.5.4: delay (in samples) of adaptive code index i, ascending, and the hex
// value transmitted for it.
double fs1016_adaptive_delay(std::size_t index);
std::uint8_t fs1016_adaptive_hex(std::size_t index);
// 3.5.3: weight j (-20..19) for fraction f, by the clause's program.
double fs1016_interp_weight(int j, double fraction);
// 3.4, 3.6, 3.7.2 tables.
double fs1016_stochastic_gain(std::size_t index);
double fs1016_adaptive_gain(std::size_t index);
std::span<const double> fs1016_lsp_table(std::size_t lsp);

// 3.9.1: the four parity bits for the eleven protected bits, in the clause's
// order PD(1)-5, PD(1)-6, PD(1)-7, PG(1)-4, PG(2)-4, PD(3)-5, PD(3)-6,
// PD(3)-7, PG(3)-4, PG(4)-4, SP. Bit k of the result is HP-k.
std::uint8_t fs1016_hamming_parity(std::uint16_t protected_bits);

// 3.8.2 and 3.9.1. sync is the SY bit.
Fs1016Bits fs1016_pack(const Fs1016Params& params, bool sync);
struct Fs1016Unpacked {
    Fs1016Params params;
    bool sync = false;
    // 3.9.2 outcome: syndrome is the XOR of computed and received parity;
    // corrected says one protected bit was inverted because of it.
    std::uint8_t syndrome = 0;
    bool corrected = false;
};
Fs1016Unpacked fs1016_unpack(const Fs1016Bits& bits);

// LPC (a[0] = 1, a[1..10]) <-> LSP frequencies in Hz. See note 3.
std::array<double, 10> fs1016_lpc_to_lsp(const std::array<double, 11>& a);
std::array<double, 11> fs1016_lsp_to_lpc(const std::array<double, 10>& lsp_hz);

struct Fs1016FrameReport {
    bool sync = false;
    bool sync_as_expected = true;  // 3.8.3 alternation held
    std::uint8_t syndrome = 0;
    bool corrected = false;
    std::size_t frames = 0;
    std::size_t corrections = 0;   // running total of 3.9 corrections
};

class Fs1016Decoder {
public:
    explicit Fs1016Decoder(bool postfilter = false);

    // 240 samples in [-1, 1].
    std::array<float, kFs1016FrameSamples> decode(const Fs1016Bits& bits);
    std::array<float, kFs1016FrameSamples> decode_params(const Fs1016Params& params);

    const Fs1016FrameReport& last_frame() const { return report_; }
    std::string describe_last_frame() const;

private:
    void synthesise(const Fs1016Params& params, std::array<float, kFs1016FrameSamples>& out);

    bool postfilter_;
    std::array<double, kFs1016AdaptiveRegister> adaptive_{};
    std::array<double, 10> synth_mem_{};
    std::array<double, 10> prev_lsp_{};
    std::size_t prev_pd_index_ = 0;
    std::array<double, 10> pf_zero_mem_{};
    std::array<double, 10> pf_pole_mem_{};
    double pf_tilt_mem_ = 0.0;
    bool expect_sync_ = false;
    bool first_ = true;
    Fs1016FrameReport report_;
};

class Fs1016Encoder {
public:
    Fs1016Encoder();

    // Takes 240 samples in [-1, 1] and returns the frame for the previous 240
    // (note 7), so the output is one frame late. The first call returns the
    // frame for 30 ms of silence.
    Fs1016Bits encode(std::span<const float> frame);
    const Fs1016Params& last_params() const { return params_; }

private:
    std::array<double, 2 * kFs1016FrameSamples> speech_{};  // previous, current
    std::array<double, 10> prev_lsp_{};
    std::array<double, kFs1016AdaptiveRegister> adaptive_{};
    std::array<double, 10> fir_mem_{};      // past speech for A(z)
    std::array<double, 10> wiir_mem_{};     // weighted speech 1/A(z/g)
    std::array<double, 10> h_mem_{};        // excitation through 1/A(z/g)
    std::size_t prev_pd_index_ = 0;
    bool sync_ = false;
    Fs1016Params params_;
};

}  // namespace revenant::decode
