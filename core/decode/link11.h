namespace revenant::decode {

// 5.1.3.1 and table II.
inline constexpr double kLink11DopplerHz = 605.0;
inline constexpr double kLink11SyncHz = 2915.0;
inline constexpr double kLink11FirstHz = 935.0;
inline constexpr double kLink11SpacingHz = 110.0;
inline constexpr int kLink11DataTones = 15;  // 935..2365 and 2915

// Data tone d (0..14) carries bit locations 2d (even) and 2d + 1 (odd).
[[nodiscard]] constexpr double link11_tone_hz(int d) {
    return d < 14 ? kLink11FirstHz + kLink11SpacingHz * d : kLink11SyncHz;
}

// 5.1.3.4.
enum class Link11Rate : std::uint8_t { Fast, Slow };  // 13.33 ms, 22 ms
[[nodiscard]] constexpr double link11_frame_seconds(Link11Rate r) {
    return r == Link11Rate::Fast ? 0.04 / 3.0 : 0.022;
}

// Table I: the phase change, in units of -45 degrees (1, 3, 5, 7), for the
// even and odd bit of a tone.
[[nodiscard]] int link11_phase_step(int even, int odd);

// Table III. Addresses are octal 01 to 76; the start code is listed with
// them as 77 (table IV calls it so). Frames hold bit location i in bit i.
struct Link11Code {
    std::uint32_t first = 0;
    std::uint32_t second = 0;
};
[[nodiscard]] Link11Code link11_start_code();
[[nodiscard]] Link11Code link11_address_code(int address);
inline constexpr std::uint32_t kLink11AllOnes = (1U << 30U) - 1U;

// 5.2.4.1: the 30-bit frame for a 24-bit word (locations 0 to 23).
[[nodiscard]] std::uint32_t link11_encode_word(std::uint32_t data);

struct Link11WordCheck {
    std::uint32_t data = 0;  // the 24 bits, after any correction
    // 0 clean, 1 a single error corrected, -1 an error detected that could
    // not be corrected.
    int status = 0;
};
[[nodiscard]] Link11WordCheck link11_check_word(std::uint32_t frame);

// ---------------------------------------------------------------------------
// The decoder
// ---------------------------------------------------------------------------

enum class Link11PhaseModel : std::uint8_t { Auto, Onset, Continuous };

struct Link11Config {
    dsp::SampleRate rate = 8000;
    bool auto_rate = true;
    Link11Rate frame_rate = Link11Rate::Fast;
    Link11PhaseModel phase_model = Link11PhaseModel::Auto;
    // 5.2.4.3 makes single error correction operator selectable.
    bool correct = true;
    // Engineering choices: the search span, and the share of received power
    // the 605 Hz tone must hold over two preamble frames.
    double max_offset_hz = 75.0;
    double detect_threshold = 0.4;
};

struct Link11Frame {
    enum class Kind : std::uint8_t {
        StartCode,
        ControlStop,
        PicketStop,
        AddressCode,
        Data,
        Unknown,  // a frame where a control code was due and none matched
    };
    Kind kind = Kind::Unknown;
    std::uint32_t bits = 0;      // the 30 received bit locations
    Link11WordCheck word;        // Data frames
    int address = -1;            // AddressCode, octal value as an integer
    int code_errors = 0;         // bit errors against the matched control code
};

struct Link11Transmission {
    std::int64_t position = 0;   // sample at the start of the phase reference
    Link11Rate frame_rate = Link11Rate::Fast;
    bool continuous_phase = false;
    double offset_hz = 0.0;
    int preamble_frames = 0;     // counted from the 2915 Hz reversals seen
    std::vector<Link11Frame> frames;
    // Summary: the address code sent, if any; the data words and how many
    // failed their check.
    int address = -1;
    bool started = false;
    bool picket_stop = false;
    bool control_stop = false;
    int words = 0;
    int corrected = 0;
    int failed = 0;
};

class Link11Decoder {
public:
    [[nodiscard]] static Expected<Link11Decoder> create(const Link11Config& config);

    // Appends each transmission as it ends. The output depends only on the
    // concatenated input, never on how it was split into calls.
    void process(dsp::ConstRealSpan audio, std::vector<Link11Transmission>& out);
    void flush(std::vector<Link11Transmission>& out);
    void reset();

private:
    using Cplx = std::complex<double>;
    explicit Link11Decoder(const Link11Config& config);

    enum class State : std::uint8_t { Search, Timing, Data };

    [[nodiscard]] Cplx correlate(double hz, std::int64_t start) const;
    [[nodiscard]] float at(std::int64_t i) const { return buf_[static_cast<std::size_t>(i - base_)]; }
    bool step();
    bool search();
    bool timing();
    bool frame();
    void finish();
    void trim();

    Link11Config config_;
    double fs_ = 0.0;
    int window_ = 0;
    int hop_ = 0;

    std::vector<float> buf_;
    std::int64_t base_ = 0;
    std::int64_t end_ = 0;

    State state_ = State::Search;
    std::int64_t next_hop_ = 0;
    std::int64_t detect_ = 0;
    double offset_ = 0.0;

    Link11Rate rate_ = Link11Rate::Fast;
    double period_ = 0.0;   // samples per frame
    bool continuous_ = false;
    double t0_ = 0.0;       // window start of the phase reference frame
    int index_ = 0;
    int preamble_frames_ = 0;
    std::array<Cplx, 16> prev_{};
    double rho_ = 0.0;
    double doppler_power_ = 0.0;
    int weak_ = 0;
    std::vector<std::uint32_t> bits_;
    bool done_ = false;
    std::vector<Link11Transmission> pending_;
};

}  // namespace revenant::decode
