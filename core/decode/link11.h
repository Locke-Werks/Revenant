// Link-11 (TADIL A) conventional waveform (CLEW): receiver audio to frames of
// 30 bits, control codes, and 24-bit data words with their error check.
//
// SPECIFICATION
//
// MIL-STD-188-203-1A, 8 January 1988, distribution statement A (approved for
// public release, unlimited), read from everyspec.com as a scanned document.
// A US Government work; the tables below are transcribed from it. Clauses
// used:
//
//   5.1.3     the 16 tones: 605 Hz Doppler, 935 to 2365 Hz on 110 Hz, and
//             2915 Hz; 5.1.3.2 and table I, the dibit to phase change; table
//             II, the bit locations each tone carries; 5.1.3.3 the levels
//   5.1.3.4   2250 bit/s on 13.33 ms frames, or 1364 bit/s on 22 ms
//   5.1.4     the frame sequence: five preamble frames of 605 and 2915 Hz,
//             the 2915 Hz tone reversed every frame; one phase reference
//             frame; the information segment of figures 3 and 4
//   5.1.4.3.1 control codes of two 30-bit frames, recognised with up to four
//             bit errors a frame; table III, the code library, and its notes
//             1 and 2
//   5.2.4     the Hamming code: six parity bits in locations 24 to 29 over
//             the 24 data bits, odd parity, the check assignments of 5.2.4.1
//             and table V, single error correction
//   5.2.7     Doppler correction from the 605 Hz tone over +/- 75 Hz
//
// Table III's note 1 gives the generator of the sequence the codes are drawn
// from as "x^5 + x + 1" in the scanned copy. That polynomial is reducible and
// has no 63-bit maximal sequence; the table itself has 63 codes, each the
// previous one advanced a bit. The codes here are generated by the
// recurrence s[n] = s[n-1] xor s[n-6] (x^6 + x^5 + 1, the reverse of
// x^6 + x + 1), which reproduces every row of table III that the tests
// compare, so the scan most likely lost the 6.
//
// One reading the document leaves open, an assumption: a data tone's phase
// change "referenced to the phase of that tone in the previous frame" is
// taken as the change in its instantaneous phase from one frame onset to the
// next, so a tone's phase within a frame runs from that frame's onset. The
// other reading (a tone that runs continuously, its phase stepped at each
// onset) adds a fixed 2 pi f T to every change; the receiver tries both on
// the first frames and keeps whichever makes the changes odd multiples of
// 45 degrees.
//
// WHERE THIS STOPS
//
// At the bits. What the 24-bit data words mean is MIL-STD-6011, distribution
// limited, and is not attempted. The DTS-to-computer interface (appendices
// D1 to D3), net cycle supervision and the SLEW waveform are not covered;
// each transmission is reported with its frames, its control codes and the
// net participating unit address it names.
//
// CLEAN ROOM
//
// No Link-11 implementation was read.

#pragma once

#include <array>
#include <complex>
#include <cstddef>
#include <cstdint>
#include <span>
